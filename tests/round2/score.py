"""Round 2 scoring: reviewers C (strict literal) and D (practical) vs tests/round2/answer_key.csv. Run from the repository root: python3 tests/round2/score.py. Judgments hard-coded below."""
import csv,re
import json
def load_key(path, as_keyed=True):
    """Read answer_key.csv. With as_keyed=True, restore the original (pre-adjudication) key
    values from the original_key column, so the score reproduces the 'as keyed' numbers;
    adjudication is applied by the judgments hard-coded in this script, as in the original run."""
    out = {}
    for r in csv.DictReader(open(path)):
        if as_keyed and r.get('original_key'):
            r.update(json.loads(r['original_key']))
        out[r['id']] = r
    return out
K=load_key('tests/round2/answer_key.csv')
C={r['id']:r for r in csv.DictReader(open('tests/round2/verdicts_C.csv'))}
D={r['id']:r for r in csv.DictReader(open('tests/round2/verdicts_D.csv'))}
ent=lambda r:r['entry_ids'].split(';')[0].strip()
# label judgments for flags on fallacy passages. Default acceptable (name/alias of entry matches key); exceptions:
WRONG={('Q049','cherry-picking')}                       # Simpson's/aggregation is not a selected subset
JUDGED={('Q003','cum-hoc'):'key lists false cause; cum hoc is the specific false-cause form and correctly names the move (less precise than confounding by indication)',
 ('Q003','common-cause'):'= confounding by indication (severity causes both referral and death)',
 ('Q010','base-rate-fallacy'):'KEY OVERRULED: P(traits|fraud) read as P(fraud|traits), ignoring how common the traits are among legitimate charities (the key reason itself says so)',
 ('Q049','common-cause'):'= confounding (case mix), key lists confounding',
 ('Q007','avoiding-the-question'):'= evasion / ignoring the question',
 ('Q027','cherry-picking'):'key lists misleading statistics; stated bleeding risk ignored; relative-risk framing has no entry',
 ('Q098','appeal-to-accomplishment'):'= appeal to inappropriate authority (achievement in another field)',
 ('Q045','multiple-comparisons'):'= multiple comparisons fallacy',
 ('Q038','anecdotal-evidence'):'listed'}
STRICT_FAIL={('Q003','cum-hoc'),('Q003','common-cause'),('Q010','base-rate-fallacy'),('Q049','common-cause'),('Q027','cherry-picking'),('Q098','appeal-to-accomplishment'),('Q007','avoiding-the-question')}
def agreed(i):
    a,b=C[i]['verdict'],D[i]['verdict']
    v='flag' if a==b=='flag' else ('possible issue' if 'flag' in (a,b) or 'possible issue' in (a,b) else 'no issue')
    la,lb=ent(C[i]),ent(D[i])
    return {'verdict':v,'entry_ids':la if la==lb else la+'|'+lb,'error_sentence':C[i]['error_sentence']+' || '+D[i]['error_sentence']}
R={'C (strict)':C,'D (practical)':D,'Agreed':{i:agreed(i) for i in K}}
tok=lambda s:set(re.findall(r"[a-z0-9']+",s.lower()))
def es_match(key,rev):
    kt=tok(key); 
    return bool(kt) and len(kt&tok(rev))/len(kt)>=0.6
def score(rv):
    s=dict(L_h=0,L_s=0,N_h=0,N_s=0,ok=0,wrong=0,split=0,soft=0,hard=0,strict=0,es=0,es_n=0)
    for i,k in K.items():
        v=rv[i]['verdict']; t=k['truth']
        if t=='legit': s['L_h']+=v=='flag'; s['L_s']+=v=='possible issue'
        elif t=='no-argument': s['N_h']+=v=='flag'; s['N_s']+=v=='possible issue'
        else:
            if v=='flag':
                labs=rv[i]['entry_ids'].split('|'); ok=[(i,l) not in WRONG for l in labs]
                if len(labs)>1 and any(ok) and not all(ok): s['split']+=1
                elif all(ok): s['ok']+=1
                else: s['wrong']+=1
                s['strict']+=all((i,l) not in WRONG|STRICT_FAIL for l in labs)
            elif v=='possible issue': s['soft']+=1
            else: s['hard']+=1
            if v in ('flag','possible issue'):
                s['es_n']+=1; s['es']+=es_match(k['error_sentences'],rv[i]['error_sentence'])
    return s
S={n:score(r) for n,r in R.items()}
vs=['flag','possible issue','no issue']; n=len(K)
agree=sum(C[i]['verdict']==D[i]['verdict'] for i in K)
pa={v:sum(C[i]['verdict']==v for i in K)/n for v in vs}; pb={v:sum(D[i]['verdict']==v for i in K)/n for v in vs}
pe=sum(pa[v]*pb[v] for v in vs); kappa=(agree/n-pe)/(1-pe)
both=[i for i in K if C[i]['verdict']==D[i]['verdict']=='flag']; lab=sum(ent(C[i])==ent(D[i]) for i in both)
bothpi=[i for i in K if C[i]['verdict']==D[i]['verdict']=='possible issue']
esm=[i for i in K if K[i]['truth']=='fallacy' for R_ in [C,D] if R_[i]['verdict']!='no issue' and not es_match(K[i]['error_sentences'],R_[i]['error_sentence'])]
