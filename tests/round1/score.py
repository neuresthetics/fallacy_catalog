"""Round 1 scoring: reviewers A and B vs tests/round1/answer_key.csv. Run from the repository root: python3 tests/round1/score.py. Label judgments are in LABEL_WRONG / BORDER below."""
import csv
import json
def load_key(path, as_keyed=True):
    """Read answer_key.csv. With as_keyed=True, restore the original (pre-adjudication) key
    values from the original_key column, so the score reproduces the 'as keyed' numbers;
    adjudication is applied by the judgments hard-coded in this script, as in the original run."""
    out = {}
    for r in csv.DictReader(open(path)):
        if as_keyed and r.get('original_key'):
            r.update(json.loads(r['original_key']))
        out[r['id']] = r
    return out
K=load_key('tests/round1/answer_key.csv')
A={r['id']:r for r in csv.DictReader(open('tests/round1/verdicts_A.csv'))}
B={r['id']:r for r in csv.DictReader(open('tests/round1/verdicts_B.csv'))}
ent=lambda r:r['entry_ids'].split(';')[0].split('/')[0].replace('(checked)','').replace('(checked, as a rebuttal)','').strip()
# label acceptability by judgment (entry id -> acceptable for that passage?). Default: acceptable (auto alias match, see run log).
LABEL_WRONG={('P068','texas-sharpshooter')}            # not an alias of cherry picking / suppressed evidence
LABEL_STRICT_ONLY={('P013','four-terms'),('P080','avoiding-the-question'),('P091','appeal-to-celebrity'),('P092','courtiers-reply')}  # judged synonym, string-match would fail
# borderline: key's defensible lean -> verdict
BORDER={'P003':'no issue','P005':'no issue','P006':'flag','P009':'flag','P012':'no issue','P015':'no issue','P019':'flag',
 'P038':'no issue','P042':'no issue','P048':'no issue','P053':'no issue','P055':'no issue','P058':'no issue','P069':'no issue',
 'P086':'flag','P090':'no issue','P092':'flag','P097':'flag','P107':'flag','P110':'no issue'}
def agreed(i):
    va,vb=A[i]['verdict'],B[i]['verdict']
    if va=='flag' and vb=='flag': v='flag'
    elif 'flag' in (va,vb) or 'possible issue' in (va,vb): v='possible issue'
    else: v='no issue'
    la,lb=ent(A[i]),ent(B[i])
    return {'verdict':v,'entry_ids':la if la==lb else la+'|'+lb}
R={'A':A,'B':B,'Agreed':{i:agreed(i) for i in K}}
def score(rv):
    s=dict(hfp=0,sfp=0,hit_ok=0,hit_wrong=0,soft_miss=0,hard_miss=0,hit_split=0,b_strict=0,b_len=0,b_dis=0,strict_label_ok=0)
    for i,k in K.items():
        v=rv[i]['verdict']
        if k['truth']=='legit':
            s['hfp']+=v=='flag'; s['sfp']+=v=='possible issue'
        elif k['truth']=='fallacy':
            if v=='flag':
                labs=rv[i]['entry_ids'].split('|')
                ok=[(i,l) not in LABEL_WRONG for l in labs]
                if len(labs)>1 and any(ok) and not all(ok): s['hit_split']+=1
                elif all(ok): s['hit_ok']+=1
                else: s['hit_wrong']+=1
                s['strict_label_ok']+= all((i,l) not in LABEL_WRONG|LABEL_STRICT_ONLY for l in labs)
            elif v=='possible issue': s['soft_miss']+=1
            else: s['hard_miss']+=1
        else:
            e=BORDER[i]
            if v==e: s['b_strict']+=1
            if v==e or v=='possible issue': s['b_len']+=1
            else: s['b_dis']+=1
    return s
S={n:score(r) for n,r in R.items()}
# A-B agreement
vs=['flag','possible issue','no issue']
agree=sum(A[i]['verdict']==B[i]['verdict'] for i in K); n=len(K)
pa={v:sum(A[i]['verdict']==v for i in K)/n for v in vs}; pb={v:sum(B[i]['verdict']==v for i in K)/n for v in vs}
pe=sum(pa[v]*pb[v] for v in vs); kappa=(agree/n-pe)/(1-pe)
both=[i for i in K if A[i]['verdict']==B[i]['verdict']=='flag']
lab=sum(ent(A[i])==ent(B[i]) for i in both)
pi=[i for i in K if A[i]['verdict']==B[i]['verdict']=='possible issue']
labpi=sum(ent(A[i])==ent(B[i]) for i in pi)
allent=sum(ent(A[i])==ent(B[i]) for i in K)
o=[]
o.append("# Round 1 scores: blind reviewers A and B vs held-out answer key\n")
o.append("Catalog: fallacy_catalog @ df075a2 (v0.3.0). 120 passages: 50 legit, 50 fallacy, 20 borderline. 'Agreed' = METHOD (h): flag only if both flag; any other flag/possible-issue becomes possible issue. Generated by `score.py` (label and borderline judgments are hard-coded there).\n")
o.append("## Verdict totals\n\n| | flag | possible issue | no issue |\n|---|---|---|---|")
for nm,rv in R.items(): o.append(f"| {nm} | "+" | ".join(str(sum(rv[i]['verdict']==v for i in K)) for v in vs)+" |")
o.append("\n## Legit passages (n=50)\n\n| | hard FP (flag) | soft FP (possible issue) | correct no issue |\n|---|---|---|---|")
for nm,s in S.items(): o.append(f"| {nm} | {s['hfp']} | {s['sfp']} | {50-s['hfp']-s['sfp']} |")
o.append("\n## Fallacy passages (n=50)\n\n| | hit, acceptable label | hit, wrong label | hit, labels split (agreed only) | soft miss (possible issue) | hard miss (no issue) | strict string-match label hits* |\n|---|---|---|---|---|---|---|")
for nm,s in S.items(): o.append(f"| {nm} | {s['hit_ok']} | {s['hit_wrong']} | {s['hit_split']} | {s['soft_miss']} | {s['hard_miss']} | {s['strict_label_ok']} |")
o.append("\n\\* Strict = the entry name/alias literally matches a key name. Judged synonyms that fail a literal match: P013 four-terms ≈ equivocation (the catalog's own redirect says the ambiguous middle 'is also an instance of equivocation'), P080 avoiding-the-question ≈ evasion/ignoring the question, P091 appeal-to-celebrity ≈ celebrity endorsement/inappropriate authority. Wrong label: P068 B texas-sharpshooter (key lists cherry picking / suppressed evidence; but see errors.csv, the key accepts Texas sharpshooter for the same move at P001).")
o.append("\n## Borderline passages (n=20)\n\nKey's defensible lean mapped to a verdict (legit/lean legit → no issue; lean fallacy → flag). Strict = same verdict as the lean; lenient = same verdict or possible issue (a borderline case recorded as 'possible issue, settle by X' is within the key's defensible range); disagree = opposite hard verdict.\n\n| | strict match | lenient match | disagree |\n|---|---|---|---|")
for nm,s in S.items(): o.append(f"| {nm} | {s['b_strict']}/20 | {s['b_len']}/20 | {s['b_dis']} |")
o.append("\nPer-passage (key lean → A / B):\n\n| id | key lean | A | B | Agreed |\n|---|---|---|---|---|")
for i in BORDER: o.append(f"| {i} | {BORDER[i]} | {A[i]['verdict']} | {B[i]['verdict']} | {R['Agreed'][i]['verdict']} |")
o.append(f"\n## A–B agreement\n\n| measure | value |\n|---|---|\n| verdict agreement (120) | {agree}/120 = {agree/n:.1%} (only P086: A no issue, B possible issue) |\n| Cohen's kappa, verdict | {kappa:.3f} |\n| label agreement where both flagged | {lab}/{len(both)} (only P068: suppressed-evidence vs texas-sharpshooter) |\n| label agreement where both 'possible issue' | {labpi}/{len(pi)} |\n| primary entry examined, all 120 | {allent}/120 (no-issue rows name the entry checked and rejected; differences there are which look-alike was checked first, not disagreements) |\n")
o.append("**Independence caveat.** A and B produced the same six 'possible issue' calls, raised the same catalog problems in nearly the same words, and adopted the same unwritten fix for METHOD (f). Their 99% agreement measures consistency of the catalog-plus-reviewer setup, not two independent judgments. The 0 false positives / 0 hard misses also reflect a test set whose fallacies are mostly textbook-clean; the real stress is in the 20 borderline cases and in the 8 flags that only survived because both reviewers read METHOD (f) non-literally (see FIXES.md F1).\n")
o.append("## Errors by fault class (see errors.csv)\n\n| class | passages |\n|---|---|\n| catalog problem (caused an error or soft deviation) | P068 (label split), P005, P009, P019, P042, P097, P107 |\n| reviewer error | P086 (A: no issue) |\n| answer-key error / over-narrow key | P013 (equivalent label rejected), P068 (Texas sharpshooter accepted at P001 but not here), P009 (lists confirmation bias, which the catalog forbids flagging; lean depends on outside literature), P019 and P097 (lean-fallacy calls that conflict with the method's hedge and charity rules) |\n| latent catalog problem (right verdict, reached only by reading past the catalog) | P001, P017, P022, P046, P054, P088, P113 (METHOD f); P012, P032, P057, P084, P092, P118, P006, P110, P076, P049, P015/P021/P036/P115 |\n")
open('tests/round1/scores.md','w').write("\n".join(o))
print("\n".join(o))
